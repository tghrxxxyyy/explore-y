def find_disclaimer_line(content):
    """Find the line number where disclaimer or last line starts"""
    lines = content.split('\n')
    # Look for disclaimer patterns
    for i in range(len(lines) - 1, max(0, len(lines) - 20), -1):
        line = lines[i].strip()
        if line.startswith('*') and ('免责声明' in line or '仅作科普参考' in line or '不构成投资建议' in line or '不构成学术定论' in line or '具时效性' in line or '仅供知识普及' in line or '以实际面试为准' in line or '以仓库当前数据为准' in line or '以主管部门最新规定为准' in line or '不构成购买建议' in line):
            return i
        if line.startswith('*') and ('数据为' in line or '本文为' in line or '提示' in line):
            return i
    # If no disclaimer found, return the last line
    return len(lines) - 1

def expand_file(filepath, content_to_add):
    """Expand a file by adding content before the disclaimer"""
    with open(filepath, 'r', encoding='utf-8') as f:
        content = f.read()
    
    disclaimer_idx = find_disclaimer_line(content)
    if disclaimer_idx == -1:
        print(f"Warning: Disclaimer not found in {filepath}")
        return False
    
    lines = content.split('\n')
    
    # Find where to insert (before --- if present, or before disclaimer)
    insert_idx = disclaimer_idx
    if insert_idx > 0 and lines[insert_idx - 1].strip() == '---':
        insert_idx -= 1
    
    # Build new content
    before = '\n'.join(lines[:insert_idx])
    after = '\n'.join(lines[insert_idx:])
    
    new_content = before + '\n' + content_to_add + '\n' + after
    
    with open(filepath, 'w', encoding='utf-8') as f:
        f.write(new_content)
    
    return True

