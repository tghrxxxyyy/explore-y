# Process files
def process_file(filepath, city_name, content_data):
    with open(filepath, 'r', encoding='utf-8') as f:
        content = f.read()
    
    # Find the disclaimer line
    disclaimer = "> ⚠️ 票价与开放时间以景区官方公示为准（数据参考 2026-07）。60 周岁以上老人、6 周岁（或 1\.2 米）以下儿童、现役军人、残疾人等多享免票或半价，出行请带好证件。"
    
    if disclaimer not in content:
        print(f"Warning: Disclaimer not found in {filepath}")
        return
    
    # Find the food section
    food_match = re.search(r'## 🍜 .*?味道\n\n.*?\n\n', content, re.DOTALL)
    if not food_match:
        print(f"Warning: Food section not found in {filepath}")
        return
    
    old_food = food_match.group(0)
    food_desc = old_food.split('\n\n')[1].strip()
    
    # Build new food section
    new_food_section = f"""## 🍜 {city_name}味道

{food_desc}

{content_data['sections']}"""
    
    # Replace
    new_content = content.replace(old_food, new_food_section)
    
    with open(filepath, 'w', encoding='utf-8') as f:
        f.write(new_content)
    
    print(f"Successfully edited {filepath}")

